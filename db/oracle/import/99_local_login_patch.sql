DECLARE
  v NUMBER;
  PROCEDURE sync_seq(p_seq VARCHAR2, p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql INTO v;
    EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || p_seq || ' RESTART START WITH ' || v;
    DBMS_OUTPUT.PUT_LINE(p_seq || ' => ' || v);
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE(p_seq || ' skip: ' || SQLERRM);
  END;
BEGIN
  sync_seq('TBL_USER_SEQ', 'SELECT NVL(MAX(USER_ID),0)+1 FROM TBL_USER');
  sync_seq('TBL_MENU_SEQ', 'SELECT NVL(MAX(MENU_ID),0)+1 FROM TBL_MENU');
  sync_seq('TBL_MODULE_SEQ', 'SELECT NVL(MAX(MODULE_ID),0)+1 FROM TBL_MODULE');
  sync_seq('TBL_ROLE_SEQ', 'SELECT NVL(MAX(ROLE_ID),0)+1 FROM TBL_ROLE');
  sync_seq('TBL_ROLE_RIGHTS_SEQ', 'SELECT NVL(MAX(ROLE_RIGHTS_ID),0)+1 FROM TBL_ROLE_RIGHTS');
  sync_seq('TBL_FININST_BANK_SEQ', 'SELECT NVL(MAX(FININST_BANK_ID),0)+1 FROM TBL_FININST_BANK');
  sync_seq('TBL_TRANS_HEAD_SEQ', 'SELECT NVL(MAX(TRANS_HEAD_ID),0)+1 FROM TBL_TRANS_HEAD');
  sync_seq('TBL_TRANS_DETAIL_SEQ', 'SELECT NVL(MAX(TRANS_DETAIL_ID),0)+1 FROM TBL_TRANS_DETAIL');
  sync_seq('TBL_PARSER_HEAD_SEQ', 'SELECT NVL(MAX(PARSER_HEAD_ID),0)+1 FROM TBL_PARSER_HEAD');
  sync_seq('TBL_PARSER_DETAIL_SEQ', 'SELECT NVL(MAX(PARSER_DETAIL_ID),0)+1 FROM TBL_PARSER_DETAIL');
  sync_seq('TBL_REMIT_MODE_SEQ', 'SELECT NVL(MAX(REMIT_MODE_ID),0)+1 FROM TBL_REMIT_MODE');
  sync_seq('TBL_LOCATION_SEQ', 'SELECT NVL(MAX(LOCATION_ID),0)+1 FROM TBL_LOCATION');
