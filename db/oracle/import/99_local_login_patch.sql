WHENEVER SQLERROR CONTINUE
SET DEFINE OFF
SET SERVEROUTPUT ON

MERGE INTO TBL_ROLE r
USING (SELECT 21 AS ROLE_ID FROM dual) s
ON (r.ROLE_ID = s.ROLE_ID)
WHEN NOT MATCHED THEN
  INSERT (ROLE_ID, ROLE_DESCR, MC_STATUS, CREATEDATE, CREATEUSER, UPDATEINDEX)
  VALUES (21, 'Admin', 'S', SYSDATE, 1, 1);

MERGE INTO TBL_USER u
USING (SELECT 1 AS USER_ID FROM dual) s
ON (u.USER_ID = s.USER_ID)
WHEN MATCHED THEN UPDATE SET
  LDAP_EMPCODE = '1001',
  LDAP_NAME = 'Local Admin',
  LDAP_EMAIL = 'admin@localhost',
  EMAIL = 'admin@localhost',
  USERNAME = 'admin',
  USERCODE = 'admin',
  EMP_CODE = '1001',
  EMPLOYEE_NO = '1001',
  IS_ACTIVE = 'Y',
  STATUS_CODE = 'A',
  ROLE_ID = 21,
  LASTUPDATEDATE = SYSDATE
WHEN NOT MATCHED THEN INSERT (
  USER_ID, USERCODE, USERNAME, EMP_CODE, EMPLOYEE_NO, IS_ACTIVE, STATUS_CODE,
  EMAIL, LDAP_NAME, LDAP_EMAIL, LDAP_EMPCODE, ROLE_ID, LOCATION_ID, ORGANIZATION_ID,
  CREATEDATE, CREATEUSER, UPDATEINDEX
) VALUES (
  1, 'admin', 'admin', '1001', '1001', 'Y', 'A',
  'admin@localhost', 'Local Admin', 'admin@localhost', '1001', 21, 1, 1,
  SYSDATE, 1, 1
);

UPDATE TBL_USER SET
  LDAP_EMPCODE = '1001',
  LDAP_NAME = 'Local Admin',
  LDAP_EMAIL = 'admin@localhost',
  IS_ACTIVE = 'Y',
  STATUS_CODE = 'A',
  ROLE_ID = 21
WHERE USER_ID = 1;

DELETE FROM TBL_ROLE_RIGHTS WHERE ROLE_ID = 21;
INSERT INTO TBL_ROLE_RIGHTS (
  ROLE_RIGHTS_ID, ROLE_ID, MENU_ID, HIDE_YN, SELECT_ALLOWED, INSERT_ALLOWED,
  UPDATE_ALLOWED, AUTHORIZE_ALLOWED, MC_STATUS, CREATEUSER, CREATEDATE, UPDATEINDEX
)
SELECT
  NVL((SELECT MAX(ROLE_RIGHTS_ID) FROM TBL_ROLE_RIGHTS), 0) + ROWNUM,
  21, MENU_ID, 'N', 'Y', 'Y', 'Y', 'Y', 'S', 1, SYSDATE, 1
FROM TBL_MENU
WHERE MENU_PATH IS NOT NULL;

DELETE FROM TBL_GLOBAL_CONFIG WHERE KEY_NAME IN ('MT102_FILE_PATH','AUTO_FILE_UPLOAD_PATH','NACTA_FILE_PATH');
