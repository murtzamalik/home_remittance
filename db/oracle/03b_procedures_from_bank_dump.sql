CREATE OR REPLACE EDITIONABLE PROCEDURE "PROC_TRANS_VALIDATE" 
(
  P_TRANS_HEAD_ID IN NUMBER 
, P_USER_ID IN NUMBER 
, P_STATUS OUT NUMBER 
, P_STATUSDESCR OUT VARCHAR2 
) AS 
    -- CURSOR TO CHECK TRANS HEAD
    CURSOR C_TRANS_HEAD IS
    SELECT STATUS
      FROM TBL_TRANS_HEAD
     WHERE TRANS_HEAD_ID = P_TRANS_HEAD_ID;
     
    VC_TRANS_HEAD C_TRANS_HEAD%ROWTYPE; 
    
    -- CURSOR FOR AML/NACTA BENEFICIARY CNIC VALIDATION
    CURSOR C_VAL_CNIC(V_BEN_CNIC VARCHAR2) IS
    SELECT *
      FROM TBL_NACTA_LIST
     WHERE CNIC = V_BEN_CNIC;
    
    VC_VAL_CNIC C_VAL_CNIC%ROWTYPE;
    
    -- CURSOR FOR AML/NACTA BENEFICIARY NAME VALIDATION
    CURSOR C_VAL_BEN_NAME(V_BEN_NAME VARCHAR2) IS
    SELECT *
      FROM TBL_NACTA_LIST
     WHERE UPPER(TRIM(NAME)) = UPPER(TRIM(V_BEN_NAME));
    
    VC_VAL_BEN_NAME C_VAL_BEN_NAME%ROWTYPE;
    
    -- CURSOR FOR AML/NACTA REMITTER NAME VALIDATION
    CURSOR C_VAL_REM_NAME(V_REM_NAME VARCHAR2) IS
    SELECT *
      FROM TBL_NACTA_LIST
     WHERE UPPER(TRIM(NAME)) = UPPER(TRIM(V_REM_NAME)); 
     
    VC_VAL_REM_NAME C_VAL_REM_NAME%ROWTYPE;
    
BEGIN
  
  OPEN C_TRANS_HEAD;
  FETCH C_TRANS_HEAD INTO VC_TRANS_HEAD;
  IF C_TRANS_HEAD%NOTFOUND THEN
    
    CLOSE C_TRANS_HEAD;
    P_STATUS := 0;
    P_STATUSDESCR := 'INVALID FILE ID';
    RETURN;
  END IF;
  CLOSE C_TRANS_HEAD;
  
  IF VC_TRANS_HEAD.STATUS NOT IN ('O') THEN
  
    P_STATUS := 0;
    P_STATUSDESCR := 'FILE ALREADY PROCESSED';
    RETURN;
    
  END IF;
  
  SAVEPOINT VDT;
  
  FOR I IN (SELECT *
              FROM TBL_TRANS_DETAIL
             WHERE TRANS_HEAD_ID = P_TRANS_HEAD_ID
               AND STATUS = 'O' AND TRANS_TYPE IS NOT NULL
             ORDER BY TRANS_DETAIL_ID)
  LOOP
    
    OPEN C_VAL_CNIC(I.BENEFICIARY_CNIC);
    FETCH C_VAL_CNIC INTO VC_VAL_CNIC;
    IF C_VAL_CNIC%FOUND THEN
        
        CLOSE C_VAL_CNIC;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'VBC',
               STATUS_DESCR = 'BENEFICIARY CNIC FOUND IN '||VC_VAL_CNIC.PROCESS_NAME||' LIST',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
        CONTINUE;
        
    END IF;
    CLOSE C_VAL_CNIC;
    
    
    OPEN C_VAL_BEN_NAME(I.BENEFICIARY_NAME);
    FETCH C_VAL_BEN_NAME INTO VC_VAL_BEN_NAME;
    IF C_VAL_BEN_NAME%FOUND THEN
        
        CLOSE C_VAL_BEN_NAME;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'VBN',
               STATUS_DESCR = 'BENEFICIARY NAME FOUND IN '||VC_VAL_CNIC.PROCESS_NAME||' LIST',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
        CONTINUE;
        
    END IF;
    CLOSE C_VAL_BEN_NAME;
    
    OPEN C_VAL_REM_NAME(I.REMITTER_NAME);
    FETCH C_VAL_REM_NAME INTO VC_VAL_REM_NAME;
    IF C_VAL_REM_NAME%FOUND THEN
        
        CLOSE C_VAL_REM_NAME;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'VRN',
               STATUS_DESCR = 'REMITTER NAME FOUND IN '||VC_VAL_CNIC.PROCESS_NAME||' LIST',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
        CONTINUE;
        
    END IF;
    CLOSE C_VAL_REM_NAME;
    
    UPDATE TBL_TRANS_DETAIL
       SET STATUS = 'V',
           STATUS_DESCR = 'AML/NACTA VALIDATION SUCCESSFULL',
           LASTUPDATEUSER = P_USER_ID,
           LASTUPDATEDATE = SYSDATE,
           UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
     WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
  END LOOP;
  
   UPDATE TBL_TRANS_HEAD
     SET STATUS = 'V',
         LASTUPDATEUSER = P_USER_ID,
         LASTUPDATEDATE = SYSDATE,
         UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
   WHERE TRANS_HEAD_ID = P_TRANS_HEAD_ID AND STATUS IN ('O');
   
   P_STATUS := 1;
   P_STATUSDESCR := 'VALIDATION DONE SUCCESSFULLY';
   

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO VDT;
        P_STATUS := 0;
        P_STATUSDESCR := SQLCODE||'-'||SQLERRM;
        
END PROC_TRANS_VALIDATE;

