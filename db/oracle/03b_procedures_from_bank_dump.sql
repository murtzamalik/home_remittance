CREATE OR REPLACE EDITIONABLE PROCEDURE "PROC_BIFURCATE_VALIDATE" 
(
  P_TRANS_DETAIL_ID IN NUMBER,
  P_USER_ID IN NUMBER,
  P_STATUS OUT NUMBER, 
  P_STATUSDESCR OUT VARCHAR2 
) AS 
    -- CURSOR TO CHECK TRANS DETAIL
    CURSOR C_TRANS_DETAIL IS
    SELECT STATUS
      FROM TBL_TRANS_DETAIL
     WHERE TRANS_DETAIL_ID = P_TRANS_DETAIL_ID;

    VC_TRANS_DETAIL C_TRANS_DETAIL%ROWTYPE;
    
    -- CURSOR FOR AML/NACTA BENEFICIARY CNIC VALIDATION
    CURSOR C_VAL_CNIC(V_BEN_CNIC VARCHAR2) IS
    SELECT *
      FROM TBL_NACTA_LIST
     WHERE CNIC = V_BEN_CNIC;
    
    VC_VAL_CNIC C_VAL_CNIC%ROWTYPE;
    
    -- CURSOR FOR AML/NACTA BENEFICIARY NAME VALIDATION
    CURSOR C_VAL_BEN_NAME(V_BEN_NAME VARCHAR2) IS
    SELECT *
      FROM TBL_NACTA_LIST
     WHERE UPPER(TRIM(NAME)) = UPPER(TRIM(V_BEN_NAME));
    
    VC_VAL_BEN_NAME C_VAL_BEN_NAME%ROWTYPE;
    
    -- CURSOR FOR AML/NACTA REMITTER NAME VALIDATION
    CURSOR C_VAL_REM_NAME(V_REM_NAME VARCHAR2) IS
    SELECT *
      FROM TBL_NACTA_LIST
     WHERE UPPER(TRIM(NAME)) = UPPER(TRIM(V_REM_NAME)); 
     
    VC_VAL_REM_NAME C_VAL_REM_NAME%ROWTYPE;
    
    -- CURSOR TO CHECK AMOUNT CAPPING 
    CURSOR C_AMOUNT_CAPPING(V_REMIT_CODE VARCHAR2) IS
    SELECT NVL(AMOUNT_CAPPING,0) AMOUNT_CAPPING
      FROM TBL_REMIT_MODE
     WHERE REMIT_CODE = V_REMIT_CODE;
    
    V_AMOUNT_CAPPING NUMBER;
    V_STATUS VARCHAR2(2);
    V_STATUSDESCR VARCHAR2(200);
    
BEGIN

  OPEN C_TRANS_DETAIL;
  FETCH C_TRANS_DETAIL INTO VC_TRANS_DETAIL;
  IF C_TRANS_DETAIL%NOTFOUND THEN

    CLOSE C_TRANS_DETAIL;
    P_STATUS := 0;
    P_STATUSDESCR := 'INVALID ID';
    RETURN;
  END IF;
  CLOSE C_TRANS_DETAIL;


  IF VC_TRANS_DETAIL.STATUS NOT IN ('N1') THEN

    P_STATUS := 0;
    P_STATUSDESCR := 'RECORD ALREADY PROCESSED';
    RETURN;

  END IF;

  SAVEPOINT SP;
  -- BIFURCATION PROCESS 
  FOR I IN (SELECT *
              FROM TBL_TRANS_DETAIL
             WHERE TRANS_DETAIL_ID = P_TRANS_DETAIL_ID
               AND STATUS = 'N1' AND TRANS_AMD = 'Y')
  LOOP

    IF I.BENEFICIARY_ACCOUNT_NO IS NULL AND UPPER(I.BENEFICIARY_BANK_NAME) = 'JSBL' THEN
        -- CASH OVER COUNTER
        
        OPEN C_AMOUNT_CAPPING('OC');
        FETCH C_AMOUNT_CAPPING INTO V_AMOUNT_CAPPING;
        CLOSE C_AMOUNT_CAPPING;
        
        IF V_AMOUNT_CAPPING < I.AMOUNT THEN
            V_STATUS := 'LE';
            V_STATUSDESCR := 'Limit Exceed';
        ELSE
            V_STATUS := 'O';
        END IF;
        
        
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'OC',
               STATUS = V_STATUS,
               STATUS_DESCR = V_STATUSDESCR,
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;

        CONTINUE;

    END IF;

    IF I.BENEFICIARY_ACCOUNT_NO IS NULL AND UPPER(I.BENEFICIARY_BANK_NAME) IN ('MCB','ABL') THEN
        -- CHANNEL PARTNER
        
        OPEN C_AMOUNT_CAPPING('CO');
        FETCH C_AMOUNT_CAPPING INTO V_AMOUNT_CAPPING;
        CLOSE C_AMOUNT_CAPPING;
        
        IF V_AMOUNT_CAPPING < I.AMOUNT THEN
            V_STATUS := 'LE';
            V_STATUSDESCR := 'Limit Exceed';
        ELSE
            V_STATUS := 'O';
        END IF;
        
        
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'CO',
               STATUS = V_STATUS,
               STATUS_DESCR = V_STATUSDESCR,
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;

        CONTINUE;

    END IF;

    IF I.BENEFICIARY_ACCOUNT_NO IS NULL AND UPPER(I.BENEFICIARY_BANK_NAME) NOT IN ('JSBL','MCB','ABL') THEN
        -- INCOMPLETE
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'IC',
               STATUS = 'O',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;

        CONTINUE;

    END IF;

    IF I.BENEFICIARY_ACCOUNT_NO IS NOT NULL AND UPPER(I.BENEFICIARY_BANK_NAME) = 'JSBL' THEN
        -- OWN BANK TRANSFER/FT 
        
        OPEN C_AMOUNT_CAPPING('AC');
        FETCH C_AMOUNT_CAPPING INTO V_AMOUNT_CAPPING;
        CLOSE C_AMOUNT_CAPPING;
        
        IF V_AMOUNT_CAPPING < I.AMOUNT THEN
            V_STATUS := 'LE';
            V_STATUSDESCR := 'Limit Exceed';
        ELSE
            V_STATUS := 'O';
        END IF;
        
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'AC',
               STATUS = V_STATUS,
               STATUS_DESCR = V_STATUSDESCR,
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;

        CONTINUE;

    END IF;

    IF I.BENEFICIARY_ACCOUNT_NO IS NOT NULL AND UPPER(I.BENEFICIARY_BANK_NAME) NOT IN ('JSBL') THEN
        -- IBFT
        
        OPEN C_AMOUNT_CAPPING('IB');
        FETCH C_AMOUNT_CAPPING INTO V_AMOUNT_CAPPING;
        CLOSE C_AMOUNT_CAPPING;
        
        IF V_AMOUNT_CAPPING < I.AMOUNT THEN
            V_STATUS := 'LE';
            V_STATUSDESCR := 'Limit Exceed';
        ELSE
            V_STATUS := 'O';
        END IF;
        
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'IB',
               STATUS = V_STATUS,
               STATUS_DESCR = V_STATUSDESCR,
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;

        CONTINUE;

    END IF;

    -- IF TRANSACTION DOES NOT FALL IN ANY OF ABOVE CONDITIONS THEN
    UPDATE TBL_TRANS_DETAIL
       SET TRANS_TYPE = 'IC',
           STATUS = 'O',
           STATUS_DESCR = 'INVALID TRANSACTION',
           LASTUPDATEUSER = P_USER_ID,
           LASTUPDATEDATE = SYSDATE,
           UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
     WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;

  END LOOP;
  -- BIFURCATION PROCESS END
  
  -- VALIDATION PROCESS
  FOR I IN (SELECT *
              FROM TBL_TRANS_DETAIL
             WHERE TRANS_DETAIL_ID = P_TRANS_DETAIL_ID
               AND STATUS = 'O' AND TRANS_TYPE IS NOT NULL)
  LOOP
    
    OPEN C_VAL_CNIC(I.BENEFICIARY_CNIC);
    FETCH C_VAL_CNIC INTO VC_VAL_CNIC;
    IF C_VAL_CNIC%FOUND THEN
        
        CLOSE C_VAL_CNIC;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'VBC',
               STATUS_DESCR = 'BENEFICIARY CNIC FOUND IN '||VC_VAL_CNIC.PROCESS_NAME||' LIST',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
        CONTINUE;
        
    END IF;
    CLOSE C_VAL_CNIC;
    
    
    OPEN C_VAL_BEN_NAME(I.BENEFICIARY_NAME);
    FETCH C_VAL_BEN_NAME INTO VC_VAL_BEN_NAME;
    IF C_VAL_BEN_NAME%FOUND THEN
        
        CLOSE C_VAL_BEN_NAME;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'VBN',
               STATUS_DESCR = 'BENEFICIARY NAME FOUND IN '||VC_VAL_CNIC.PROCESS_NAME||' LIST',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
        CONTINUE;
        
    END IF;
    CLOSE C_VAL_BEN_NAME;
    
    OPEN C_VAL_REM_NAME(I.REMITTER_NAME);
    FETCH C_VAL_REM_NAME INTO VC_VAL_REM_NAME;
    IF C_VAL_REM_NAME%FOUND THEN
        
        CLOSE C_VAL_REM_NAME;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'VRN',
               STATUS_DESCR = 'REMITTER NAME FOUND IN '||VC_VAL_CNIC.PROCESS_NAME||' LIST',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
        CONTINUE;
        
    END IF;
    CLOSE C_VAL_REM_NAME;
    
    UPDATE TBL_TRANS_DETAIL
       SET STATUS = 'V',
           STATUS_DESCR = 'AML/NACTA VALIDATION SUCCESSFULL',
           LASTUPDATEUSER = P_USER_ID,
           LASTUPDATEDATE = SYSDATE,
           UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
     WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
  END LOOP;
  -- VALIDATION PROCESS END
   
   
   P_STATUS := 1;
   P_STATUSDESCR := 'BIFURCATION/VALIDATION DONE SUCCESSFULLY';


EXCEPTION

    WHEN OTHERS THEN
        ROLLBACK TO SP;
        P_STATUS := 0;
        P_STATUSDESCR := SQLCODE||'-'||SQLERRM;

END PROC_BIFURCATE_VALIDATE;

