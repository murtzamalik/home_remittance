CREATE OR REPLACE EDITIONABLE PROCEDURE "PROC_CHK_DUPLICATE_TRANS" 
(
  P_TRANS_HEAD_ID IN NUMBER ,
  P_USER_ID IN NUMBER ,
  P_STATUS OUT NUMBER ,
  P_STATUSDESCR OUT VARCHAR2 
) AS 

    -- CURSOR TO CHECK DUPLICATE TRANSACTION
    CURSOR C_CHK_DUPLICATE(V_FININST_BANK_ID NUMBER, V_TRANSACTION_REFERENCE VARCHAR2, V_TRANS_DETAIL_ID NUMBER) IS
    SELECT 1
      FROM TBL_TRANS_HEAD H
     INNER JOIN TBL_TRANS_DETAIL D ON H.TRANS_HEAD_ID = D.TRANS_HEAD_ID
     WHERE H.FININST_BANK_ID = V_FININST_BANK_ID
       AND D.TRANSACTION_REFERENCE = V_TRANSACTION_REFERENCE
       AND D.TRANS_DETAIL_ID NOT IN (V_TRANS_DETAIL_ID);
       
    V_CHK_DUPLICATE NUMBER;   
   
BEGIN
  
  SAVEPOINT CHK_DUP;
  
  FOR I IN (SELECT *
              FROM TBL_TRANS_HEAD H
             INNER JOIN TBL_TRANS_DETAIL D ON H.TRANS_HEAD_ID = D.TRANS_HEAD_ID
             WHERE H.TRANS_HEAD_ID = P_TRANS_HEAD_ID)
  LOOP
  
    OPEN C_CHK_DUPLICATE(I.FININST_BANK_ID, I.TRANSACTION_REFERENCE, I.TRANS_DETAIL_ID);
    FETCH C_CHK_DUPLICATE INTO V_CHK_DUPLICATE;
    
    IF C_CHK_DUPLICATE%FOUND THEN
        
        CLOSE C_CHK_DUPLICATE;
        
        UPDATE TBL_TRANS_DETAIL
           SET STATUS = 'D',
               STATUS_DESCR = 'DUPLICATE TRANSACTION',
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
         CONTINUE;
         
    END IF;
    CLOSE C_CHK_DUPLICATE;
    
  END LOOP;
  
  P_STATUS := 1;
  P_STATUSDESCR := 'DUPLICATE MARKED SUCCESSFULLY';

  
EXCEPTION 
    WHEN OTHERS THEN
        ROLLBACK TO CHK_DUP;
        P_STATUS := 0;
        P_STATUSDESCR := SQLERRM;
  
END PROC_CHK_DUPLICATE_TRANS;

