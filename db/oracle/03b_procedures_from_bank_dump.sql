        FETCH C_AMOUNT_CAPPING INTO V_AMOUNT_CAPPING;
        CLOSE C_AMOUNT_CAPPING;
        
        IF V_AMOUNT_CAPPING < I.AMOUNT THEN
            V_STATUS := 'LE';
            V_STATUSDESCR := 'Limit Exceed';
        ELSE
            V_STATUS := 'O';
        END IF;
        
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'AC',
               STATUS = V_STATUS,
               STATUS_DESCR = V_STATUSDESCR,
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
        
        CONTINUE;
        
    END IF;
    
    IF I.BENEFICIARY_ACCOUNT_NO IS NOT NULL AND UPPER(I.BENEFICIARY_BANK_NAME) NOT IN ('JSBL') THEN
        -- IBFT 
        OPEN C_AMOUNT_CAPPING('IB');
        FETCH C_AMOUNT_CAPPING INTO V_AMOUNT_CAPPING;
        CLOSE C_AMOUNT_CAPPING;
        
        IF V_AMOUNT_CAPPING < I.AMOUNT THEN
            V_STATUS := 'LE';
            V_STATUSDESCR := 'Limit Exceed';
        ELSE
            V_STATUS := 'O';
        END IF;
        
        UPDATE TBL_TRANS_DETAIL
           SET TRANS_TYPE = 'IB',
               STATUS = V_STATUS,
               STATUS_DESCR = V_STATUSDESCR,
               LASTUPDATEUSER = P_USER_ID,
               LASTUPDATEDATE = SYSDATE,
               UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
         WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
        
        CONTINUE;
        
    END IF;
    
    -- IF TRANSACTION DOES NOT FALL IN ANY OF ABOVE CONDITIONS THEN
    UPDATE TBL_TRANS_DETAIL
       SET TRANS_TYPE = 'IC',
           STATUS = 'O',
           STATUS_DESCR = 'INVALID TRANSACTION',
           LASTUPDATEUSER = P_USER_ID,
           LASTUPDATEDATE = SYSDATE,
           UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
     WHERE TRANS_DETAIL_ID = I.TRANS_DETAIL_ID;
         
  END LOOP;
  
  UPDATE TBL_TRANS_HEAD
     SET STATUS = 'O',
         LASTUPDATEUSER = P_USER_ID,
         LASTUPDATEDATE = SYSDATE,
         UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
   WHERE TRANS_HEAD_ID = P_TRANS_HEAD_ID AND STATUS = 'N';
   
   P_STATUS := 1;
   P_STATUSDESCR := 'BIFURCATION DONE SUCCESSFULLY';

   
EXCEPTION

    WHEN OTHERS THEN
        ROLLBACK TO BIFURCATE;
        P_STATUS := 0;
        P_STATUSDESCR := SQLCODE||'-'||SQLERRM;
        
END PROC_TRANS_BIFURCATE;

