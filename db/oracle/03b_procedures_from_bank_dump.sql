CREATE OR REPLACE EDITIONABLE PROCEDURE "PROC_POPULATE_MT102" 
(
  P_BATCH_NO IN NUMBER, 
  P_USER_ID IN NUMBER,
  P_MT102_HEAD_ID OUT T_MT102_HEAD_ID,
  P_STATUS OUT NUMBER,
  P_STATUSDESCR OUT VARCHAR2,
  P_HEAD_IDS OUT VARCHAR2
) AS 

    V_BANK_NAME VARCHAR2(10);
    V_DATE VARCHAR2(12);
    V_FILE_NO VARCHAR2(20);
    V_HEAD_ID NUMBER;
    V_COUNTER NUMBER;
    V_IDX NUMBER := 1;
    V_HEAD_IDX VARCHAR2(100) ;
    
     CURSOR C_BATCH_EXISTS IS
    SELECT STATUS
      FROM TBL_MT102_TEMP
     WHERE BATCH_NO = P_BATCH_NO;

    VC_BATCH_EXISTS C_BATCH_EXISTS%ROWTYPE; 

BEGIN

    OPEN C_BATCH_EXISTS;
      FETCH C_BATCH_EXISTS INTO VC_BATCH_EXISTS;
      IF C_BATCH_EXISTS%NOTFOUND THEN

        CLOSE C_BATCH_EXISTS;
        P_STATUS := 0;
        P_STATUSDESCR := 'INVALID BATCH ID';
        RETURN;
      END IF;
    CLOSE C_BATCH_EXISTS;
    
    SELECT TO_CHAR(SYSDATE,'YYMMDDHH24MI')
         INTO V_DATE
       FROM DUAL;

    P_MT102_HEAD_ID := T_MT102_HEAD_ID();

    SAVEPOINT ABC; 

    FOR I IN (SELECT B.*, A.MT102_TEMP_ID, F.BIC_CODE, F.BENEFICIARY_BANK_ACCOUNT, H.FININST_BANK_ID
                FROM TBL_MT102_TEMP A 
               INNER JOIN TBL_TRANS_DETAIL B ON A.TRANS_DETAIL_ID = B.TRANS_DETAIL_ID  
               INNER JOIN TBL_TRANS_HEAD H ON B.TRANS_HEAD_ID = H.TRANS_HEAD_ID
               INNER JOIN TBL_FININST_BANK F ON B.BENEFICIARY_BANK_NAME = F.FININST_CODE
               WHERE A.BATCH_NO = P_BATCH_NO AND A.STATUS = 'S' AND B.TRANS_TYPE= 'IB' AND B.TRANS_BT = 'Y' AND B.STATUS = 'S'
               ORDER BY B.BENEFICIARY_BANK_NAME,  A.MT102_TEMP_ID)
    LOOP

              UPDATE TBL_MT102_TEMP  
                 SET STATUS = 'I',
                     LASTUPDATEUSER = I.CREATEUSER,
                     LASTUPDATEDATE = SYSDATE,
                     UPDATEINDEX = NVL(UPDATEINDEX,0) + 1
               WHERE MT102_TEMP_ID = I.MT102_TEMP_ID;

              IF (V_BANK_NAME IS NULL OR V_BANK_NAME !=  I.BENEFICIARY_BANK_NAME) THEN

                    V_BANK_NAME := I.BENEFICIARY_BANK_NAME;
                    V_COUNTER := 0;

              END IF;

              IF (V_COUNTER = 0 OR V_COUNTER = 10) THEN

                          V_FILE_NO := 'P'||V_DATE; --V_BANK_NAME||V_DATE||LPAD(TBL_MT102_FILEREFNO_SEQ.NEXTVAL, 6,0);
                          V_HEAD_ID := TBL_MT102_HEAD_SEQ.NEXTVAL;
                          P_MT102_HEAD_ID.EXTEND(1);
                          P_MT102_HEAD_ID(V_IDX) := V_HEAD_ID;
                          V_IDX := V_IDX + 1;

                          INSERT INTO TBL_MT102_HEAD(MT102_HEAD_ID, BANK_NAME, FILE_REFERENCE_NO, TOTAL_AMOUNT, NO_OF_TRANSACTIONS, FININST_BANK_ID, STATUS, STATUSDESCR, CREATEUSER)
                                              VALUES(V_HEAD_ID, V_BANK_NAME, V_FILE_NO,   I.AMOUNT, 1, I.FININST_BANK_ID,'S', 'SUBMITTED', I.CREATEUSER);

                          INSERT INTO TBL_MT102_DETAIL (MT102_DETAIL_ID, MT102_HEAD_ID, REMITTER_NAME, REMITTER_NUMBER, REMITTER_ADDRESS,
                                                          REMITTER_COUNTRY, TRANSACTION_REFERENCE, AMOUNT, BENEFICIARY_NAME, BENEFICIARY_CNIC,
                                                          BENEFICIARY_ACCOUNT_NO, BENEFICIARY_BRANCH_CODE, BENEFICIARY_OTHER_CONTACT, 
                                                          BENEFICIARY_BANK_NAME, BENEFICIARY_BRANCH_ADD1, BENEFICIARY_BRANCH_ADD2,
                                                          BENEFICIARY_ACCOUNT_TITLE, CREATEUSER,TRANS_DETAIL_ID, BIC_CODE, BENEFICIARY_BANK_ACCOUNT)                    

                          VALUES (TBL_MT102_DETAIL_SEQ.NEXTVAL, V_HEAD_ID, I.REMITTER_NAME, I.REMITTER_NUMBER, I.REMITTER_ADDRESS,
                                          I.REMITTER_COUNTRY, I.TRANSACTION_REFERENCE, I.AMOUNT, I.BENEFICIARY_NAME, I.BENEFICIARY_CNIC,
                                          I.BENEFICIARY_ACCOUNT_NO, I.BENEFICIARY_BRANCH_CODE, I.BENEFICIARY_OTHER_CONTACT,
                                          I.BENEFICIARY_BANK_NAME, I.BENEFICIARY_BRANCH_ADD1, I.BENEFICIARY_BRANCH_ADD2,
                                          I.BENEFICIARY_ACCOUNT_TITLE, I.CREATEUSER, I.TRANS_DETAIL_ID, I.BIC_CODE, I.BENEFICIARY_BANK_ACCOUNT);

                          V_COUNTER := 1;            

              ELSE 

                         INSERT INTO TBL_MT102_DETAIL (MT102_DETAIL_ID, MT102_HEAD_ID, REMITTER_NAME, REMITTER_NUMBER, REMITTER_ADDRESS,
                                                       REMITTER_COUNTRY, TRANSACTION_REFERENCE, AMOUNT, BENEFICIARY_NAME, BENEFICIARY_CNIC,
                                                       BENEFICIARY_ACCOUNT_NO, BENEFICIARY_BRANCH_CODE, BENEFICIARY_OTHER_CONTACT, 
                                                       BENEFICIARY_BANK_NAME, BENEFICIARY_BRANCH_ADD1, BENEFICIARY_BRANCH_ADD2,
                                                       BENEFICIARY_ACCOUNT_TITLE, CREATEUSER, TRANS_DETAIL_ID, BIC_CODE, BENEFICIARY_BANK_ACCOUNT)                    

                        VALUES (TBL_MT102_DETAIL_SEQ.NEXTVAL, V_HEAD_ID, I.REMITTER_NAME, I.REMITTER_NUMBER, I.REMITTER_ADDRESS,
                                I.REMITTER_COUNTRY, I.TRANSACTION_REFERENCE, I.AMOUNT, I.BENEFICIARY_NAME, I.BENEFICIARY_CNIC,
                                I.BENEFICIARY_ACCOUNT_NO, I.BENEFICIARY_BRANCH_CODE, I.BENEFICIARY_OTHER_CONTACT,
                                I.BENEFICIARY_BANK_NAME, I.BENEFICIARY_BRANCH_ADD1, I.BENEFICIARY_BRANCH_ADD2,
                                I.BENEFICIARY_ACCOUNT_TITLE, I.CREATEUSER, I.TRANS_DETAIL_ID, I.BIC_CODE, I.BENEFICIARY_BANK_ACCOUNT);

                          UPDATE TBL_MT102_HEAD 
                             SET NO_OF_TRANSACTIONS = NO_OF_TRANSACTIONS + 1,
                                 TOTAL_AMOUNT = TOTAL_AMOUNT+I.AMOUNT 
                           WHERE MT102_HEAD_ID = V_HEAD_ID;

                          V_COUNTER := V_COUNTER+1;

              END IF;

    END LOOP;

    P_STATUS := 1;
    P_STATUSDESCR := 'MT102 GENERATED SUCCESSFULLY' ;

    FOR I IN 1..P_MT102_HEAD_ID.COUNT
    LOOP
           IF V_HEAD_IDX IS NULL THEN
              V_HEAD_IDX  := P_MT102_HEAD_ID(I);
           ELSE
              V_HEAD_IDX  :=  V_HEAD_IDX||','||P_MT102_HEAD_ID(I);
           END IF ;
    END LOOP;

    P_HEAD_IDS := V_HEAD_IDX;

EXCEPTION

      WHEN OTHERS THEN
        ROLLBACK TO SAVEPOINT ABC;
        P_STATUS := 0;
        P_STATUSDESCR := SQLCODE||'-'||SQLERRM;


END PROC_POPULATE_MT102;

